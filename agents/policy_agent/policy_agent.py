"""Policy / Risk Agent for ZT-LedgerGuard Multi-Agent Architecture.

Evaluates high-level business compliance, risk limits, and financial safety policies
on combined multi-agent context (Transaction, Reconciliation result, Fraud result).
Generates explainable, auditable PolicyEvidence for every evaluated policy.
"""

from __future__ import annotations

from datetime import datetime, timezone
from decimal import Decimal
from enum import Enum
import logging
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from agents.base_agent import AgentExecutionRecord, BaseAgent
from fraud_detection.fraud_result import FraudAnalysisResult
from reconciliation.models import Transaction
from reconciliation.reconciliation_result import ReconciliationResult, ReconciliationStatus

logger = logging.getLogger("agents.policy_agent")


class PolicyRecommendation(str, Enum):
    """Controlled recommendations from policy evaluations."""

    APPROVE = "APPROVE"
    MANUAL_REVIEW = "MANUAL_REVIEW"
    BLOCK_RECOMMENDED = "BLOCK_RECOMMENDED"


class PolicyEvidence(BaseModel):
    """Structured, explainable evidence generated by an individual policy rule."""

    policy_id: str = Field(..., description="Canonical policy rule identifier")
    triggered: bool = Field(..., description="Whether the policy condition was met")
    severity: str = Field(..., description="Severity level: LOW, MEDIUM, HIGH, CRITICAL")
    reason: str = Field(..., description="Human-readable explanation of why policy triggered or passed")
    recommendation: str = Field(
        ...,
        description="Action recommendation: APPROVE, MANUAL_REVIEW, or BLOCK_RECOMMENDED",
    )
    evidence: Dict[str, Any] = Field(default_factory=dict, description="Underlying quantitative metrics")


class PolicyAgentConfig(BaseModel):
    """Configurable thresholds for business and risk policies."""

    critical_fraud_threshold: int = Field(default=75, description="Fraud score threshold for BLOCK_RECOMMENDED")
    high_fraud_threshold: int = Field(default=50, description="Fraud score threshold for MANUAL_REVIEW")
    large_amount_limit: Decimal = Field(default=Decimal("500000.00"), description="Amount threshold requiring review")


class PolicyAgentResult(BaseModel):
    """Aggregate decision result produced by PolicyAgent."""

    agent_name: str = Field(default="PolicyAgent", description="Name of the agent")
    transaction_id: str = Field(..., description="Evaluated transaction ID")
    recommendation: str = Field(..., description="Final combined policy recommendation")
    requires_manual_review: bool = Field(..., description="Whether any policy mandated manual triage")
    block_recommended: bool = Field(..., description="Whether any policy mandated a hold/freeze")
    triggered_policies: List[PolicyEvidence] = Field(default_factory=list, description="Policies that triggered")
    all_evaluations: List[PolicyEvidence] = Field(default_factory=list, description="All evaluated policies")
    execution_record: AgentExecutionRecord = Field(..., description="Auditable agent execution record")


class PolicyAgent(BaseAgent):
    """Autonomous agent evaluating governance, risk limits, and compliance policies."""

    agent_name: str = "PolicyAgent"
    agent_version: str = "1.0.0"

    def __init__(
        self,
        config: Optional[PolicyAgentConfig] = None,
        agent_name: Optional[str] = None,
        agent_version: Optional[str] = None,
    ) -> None:
        super().__init__(
            agent_name=agent_name or "PolicyAgent",
            agent_version=agent_version or "1.0.0",
        )
        self.config = config or PolicyAgentConfig()

    def analyze(
        self,
        transaction: Transaction,
        fraud_result: Optional[FraudAnalysisResult] = None,
        reconciliation_status: Optional[str] = None,
        reconciliation_score: Optional[float] = None,
        correlation_id: Optional[str] = None,
    ) -> PolicyAgentResult:
        """Evaluate business and risk governance policies on multi-agent context."""
        started_at = datetime.now(timezone.utc)
        corr_id = correlation_id or f"CORR-POLICY-{transaction.transaction_id}"

        fraud_score = fraud_result.fraud_score if fraud_result else 0
        recon_status = (reconciliation_status or ReconciliationStatus.MATCHED.value).upper()
        recon_score = reconciliation_score if reconciliation_score is not None else 1.0

        evaluations: List[PolicyEvidence] = []

        # ----------------------------------------------------------------------
        # Policy 1: Critical Fraud Risk
        # ----------------------------------------------------------------------
        p1_triggered = fraud_score >= self.config.critical_fraud_threshold
        evaluations.append(
            PolicyEvidence(
                policy_id="CRITICAL_FRAUD_RISK",
                triggered=p1_triggered,
                severity="CRITICAL",
                reason=(
                    f"Fraud score of {fraud_score} meets or exceeds critical threshold {self.config.critical_fraud_threshold}."
                    if p1_triggered
                    else f"Fraud score of {fraud_score} is below critical threshold {self.config.critical_fraud_threshold}."
                ),
                recommendation=PolicyRecommendation.BLOCK_RECOMMENDED.value if p1_triggered else PolicyRecommendation.APPROVE.value,
                evidence={
                    "fraud_score": fraud_score,
                    "threshold": self.config.critical_fraud_threshold,
                },
            )
        )

        # ----------------------------------------------------------------------
        # Policy 2: High Fraud Risk
        # ----------------------------------------------------------------------
        p2_triggered = self.config.high_fraud_threshold <= fraud_score < self.config.critical_fraud_threshold
        evaluations.append(
            PolicyEvidence(
                policy_id="HIGH_FRAUD_RISK",
                triggered=p2_triggered,
                severity="HIGH",
                reason=(
                    f"Fraud score of {fraud_score} is in elevated range [{self.config.high_fraud_threshold}, {self.config.critical_fraud_threshold})."
                    if p2_triggered
                    else f"Fraud score of {fraud_score} is outside elevated range."
                ),
                recommendation=PolicyRecommendation.MANUAL_REVIEW.value if p2_triggered else PolicyRecommendation.APPROVE.value,
                evidence={
                    "fraud_score": fraud_score,
                    "high_threshold": self.config.high_fraud_threshold,
                    "critical_threshold": self.config.critical_fraud_threshold,
                },
            )
        )

        # ----------------------------------------------------------------------
        # Policy 3: Reconciliation Ambiguity
        # ----------------------------------------------------------------------
        p3_triggered = recon_status == ReconciliationStatus.AMBIGUOUS.value
        evaluations.append(
            PolicyEvidence(
                policy_id="RECONCILIATION_AMBIGUITY",
                triggered=p3_triggered,
                severity="HIGH",
                reason=(
                    "Reconciliation candidate matching is ambiguous; multiple competing candidates detected."
                    if p3_triggered
                    else "Reconciliation is not ambiguous."
                ),
                recommendation=PolicyRecommendation.MANUAL_REVIEW.value if p3_triggered else PolicyRecommendation.APPROVE.value,
                evidence={
                    "reconciliation_status": recon_status,
                    "reconciliation_score": recon_score,
                },
            )
        )

        # ----------------------------------------------------------------------
        # Policy 4: Reconciliation Failure / Mismatch
        # ----------------------------------------------------------------------
        p4_triggered = recon_status == ReconciliationStatus.MISMATCHED.value
        evaluations.append(
            PolicyEvidence(
                policy_id="RECONCILIATION_MISMATCH",
                triggered=p4_triggered,
                severity="MEDIUM" if fraud_score < 50 else "HIGH",
                reason=(
                    "Ledger entry exists but core financial attributes mismatched."
                    if p4_triggered
                    else "No reconciliation mismatch."
                ),
                recommendation=PolicyRecommendation.MANUAL_REVIEW.value if p4_triggered else PolicyRecommendation.APPROVE.value,
                evidence={
                    "reconciliation_status": recon_status,
                    "reconciliation_score": recon_score,
                },
            )
        )

        # ----------------------------------------------------------------------
        # Policy 5: Missing Ledger Entry
        # ----------------------------------------------------------------------
        p5_triggered = recon_status == ReconciliationStatus.NOT_FOUND.value
        evaluations.append(
            PolicyEvidence(
                policy_id="MISSING_LEDGER",
                triggered=p5_triggered,
                severity="HIGH",
                reason=(
                    "Transaction unposted; no matching ledger candidate found in core banking system."
                    if p5_triggered
                    else "Ledger entry located."
                ),
                recommendation=PolicyRecommendation.MANUAL_REVIEW.value if p5_triggered else PolicyRecommendation.APPROVE.value,
                evidence={"reconciliation_status": recon_status},
            )
        )

        # ----------------------------------------------------------------------
        # Policy 6: Combined High Risk (Elevated Fraud + Unmatched Ledger)
        # ----------------------------------------------------------------------
        p6_triggered = (fraud_score >= self.config.high_fraud_threshold) and (recon_status != ReconciliationStatus.MATCHED.value)
        evaluations.append(
            PolicyEvidence(
                policy_id="COMBINED_HIGH_RISK",
                triggered=p6_triggered,
                severity="CRITICAL",
                reason=(
                    f"Compound risk detected: elevated fraud score ({fraud_score}) coupled with non-matched reconciliation status ({recon_status})."
                    if p6_triggered
                    else "No compound risk detected."
                ),
                recommendation=PolicyRecommendation.BLOCK_RECOMMENDED.value if p6_triggered else PolicyRecommendation.APPROVE.value,
                evidence={
                    "fraud_score": fraud_score,
                    "reconciliation_status": recon_status,
                },
            )
        )

        # ----------------------------------------------------------------------
        # Policy 7: Large Amount Governance Limit
        # ----------------------------------------------------------------------
        tx_amount = Decimal(str(transaction.amount))
        p7_triggered = (tx_amount >= self.config.large_amount_limit) and (recon_status != ReconciliationStatus.MATCHED.value)
        evaluations.append(
            PolicyEvidence(
                policy_id="LARGE_AMOUNT_GOVERNANCE_LIMIT",
                triggered=p7_triggered,
                severity="HIGH",
                reason=(
                    f"Transaction amount {tx_amount} exceeds governance limit {self.config.large_amount_limit} without matched ledger entry."
                    if p7_triggered
                    else f"Transaction amount {tx_amount} satisfies governance requirements."
                ),
                recommendation=PolicyRecommendation.MANUAL_REVIEW.value if p7_triggered else PolicyRecommendation.APPROVE.value,
                evidence={
                    "amount": float(tx_amount),
                    "limit": float(self.config.large_amount_limit),
                    "reconciliation_status": recon_status,
                },
            )
        )

        # Determine overall policy recommendation using centralized precedence:
        # BLOCK_RECOMMENDED > MANUAL_REVIEW > APPROVE
        triggered_policies = [e for e in evaluations if e.triggered]

        block_recommended = any(e.recommendation == PolicyRecommendation.BLOCK_RECOMMENDED.value for e in triggered_policies)
        manual_review = any(e.recommendation in (PolicyRecommendation.MANUAL_REVIEW.value, PolicyRecommendation.BLOCK_RECOMMENDED.value) for e in triggered_policies)

        if block_recommended:
            final_rec = PolicyRecommendation.BLOCK_RECOMMENDED.value
        elif manual_review:
            final_rec = PolicyRecommendation.MANUAL_REVIEW.value
        else:
            final_rec = PolicyRecommendation.APPROVE.value

        completed_at = datetime.now(timezone.utc)

        exec_record = self.create_execution_record(
            transaction_id=transaction.transaction_id,
            decision=final_rec,
            started_at=started_at,
            completed_at=completed_at,
            evidence=[e.model_dump() for e in triggered_policies],
            correlation_id=corr_id,
            success=True,
        )

        result = PolicyAgentResult(
            agent_name=self.agent_name,
            transaction_id=transaction.transaction_id,
            recommendation=final_rec,
            requires_manual_review=manual_review,
            block_recommended=block_recommended,
            triggered_policies=triggered_policies,
            all_evaluations=evaluations,
            execution_record=exec_record,
        )

        logger.info(
            "[%s] Evaluated TX %s -> Rec: %s (Triggered: %d policies)",
            self.agent_name,
            transaction.transaction_id,
            result.recommendation,
            len(triggered_policies),
        )
        return result
